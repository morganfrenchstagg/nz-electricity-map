import Highcharts from 'highcharts'
import type { RecentData } from '../types'
import type { AggregatePeriod } from '../hooks/useAggregates'
import type { DisplayUnit } from './format'
import { nzLocalMs, todayNZ } from './time'

export interface ChartRow {
  time: string
  [code: string]: string | number
}

export interface ChartData {
  rows: ChartRow[]
  codes: string[]
}

export function extractChartData(recent: RecentData, requestedCodes: string[]): ChartData {
  const codes = requestedCodes.filter((c) => recent.series.includes(c))
  const indices = codes.map((c) => recent.series.indexOf(c) + 1) // +1: col 0 is timestamp

  const rows: ChartRow[] = recent.data.map((row) => {
    const point: ChartRow = { time: row[0] as string }
    codes.forEach((code, i) => {
      point[code] = row[indices[i]]
    })
    return point
  })

  return { rows, codes }
}

export function substationCodes(recent: RecentData, siteId: string): string[] {
  return recent.series.filter((s) => s.startsWith(siteId))
}

// A generator's code is its bus, a space and the unit, e.g. ATI2201 ATI0.
// A substation's codes are its buses' and its generators'.
export function isGeneratorCode(code: string): boolean {
  return code.includes(' ')
}

// The unit of a generator's code, e.g. ATI0 of ATI2201 ATI0
export function unitOfCode(code: string): string {
  return code.split(' ')[1]
}

// Bus codes are site, kV (3 digits) and bus number or letter, e.g. OTA1103 is
// Ōtāhuhu's 110kV bus 3. The bus is only named if another at that voltage is in siteCodes.
export function busLabel(code: string, siteCodes: string[]): string {
  const kv = parseInt(code.slice(-4, -1), 10)
  if (isNaN(kv)) return code
  const sameVoltage = code.slice(0, -1)
  const shared = siteCodes.some((c) => c !== code && !isGeneratorCode(c) && c.slice(0, -1) === sameVoltage)
  return shared ? `${kv}kV – ${code.slice(-1)}` : `${kv}kV`
}

const MINUTE_MS = 60 * 1000
const HOUR_MS = 60 * MINUTE_MS
const DAY_MS = 24 * HOUR_MS
// Dispatch data is 5-minutely, but days before 11 September 2020 are metered
// generation, per half-hour trading period
const DISPATCH_INTERVAL_MS = 5 * MINUTE_MS
const TRADING_PERIOD_MS = 30 * MINUTE_MS
// A step over this many intervals is a gap: over 20 minutes of dispatch data,
// or 2 hours of trading periods
const GAP_INTERVALS = 4

// Each day's point interval: its shortest step, which missing points don't
// lengthen. Keyed by day (days since 1970, "local time as UTC") so half-hourly
// and 5-minute days in one range each keep their own.
function intervalsByDay(times: number[]): Map<number, number> {
  const intervals = new Map<number, number>()
  for (let i = 1; i < times.length; i++) {
    const day = Math.floor(times[i] / DAY_MS)
    const step = times[i] - times[i - 1]
    if (step > 0 && Math.floor(times[i - 1] / DAY_MS) === day) {
      intervals.set(day, Math.min(step, intervals.get(day) ?? Infinity))
    }
  }
  return intervals
}

// The shortest of the days' intervals, or 5 minutes if no day has two points
export function dataInterval(times: string[]): number {
  const intervals = [...intervalsByDay(times.map(nzLocalMs)).values()]
  return intervals.length > 0 ? Math.min(...intervals) : DISPATCH_INTERVAL_MS
}

// Whether each step from the previous time is a gap: over GAP_INTERVALS of the
// longer interval of the days either side, so a switch from half-hourly to
// 5-minute data isn't drawn as a gap
function gapsBefore(times: number[]): boolean[] {
  const intervals = intervalsByDay(times)
  const intervalOn = (ms: number) => intervals.get(Math.floor(ms / DAY_MS)) ?? 0
  return times.map((ms, i) => {
    if (i === 0) return false
    const interval = Math.max(intervalOn(times[i - 1]), intervalOn(ms)) || DISPATCH_INTERVAL_MS
    return ms - times[i - 1] > GAP_INTERVALS * interval
  })
}

// Breaks a line at each gap (see gapsBefore) with a null 1ms after the point before it
export function withGaps(points: [number, number | null][]): [number, number | null][] {
  const gaps = gapsBefore(points.map(([ms]) => ms))
  const result: [number, number | null][] = []
  points.forEach((point, i) => {
    if (gaps[i]) result.push([points[i - 1][0] + 1, null])
    result.push(point)
  })
  return result
}

// MWh generated by `codes` over `rows`. Dispatch rows are MW, integrated with the
// trapezoidal rule; gaps (as withGaps draws them) are skipped, not bridged, so
// missing data doesn't inflate the total. Aggregate rows are already MWh and are
// summed. Null when there's nothing to total.
export function totalMWh(rows: ChartRow[], codes: string[], aggregate: boolean): number | null {
  if (codes.length === 0 || rows.length < (aggregate ? 1 : 2)) return null
  const rowTotal = (row: ChartRow) => codes.reduce((sum, code) => sum + ((row[code] as number) ?? 0), 0)
  if (aggregate) return rows.reduce((total, row) => total + rowTotal(row), 0)
  const times = rows.map((row) => nzLocalMs(row.time))
  const gaps = gapsBefore(times)
  let total = 0
  for (let i = 1; i < rows.length; i++) {
    const dtMs = times[i] - times[i - 1]
    if (dtMs <= 0 || gaps[i]) continue
    total += ((rowTotal(rows[i - 1]) + rowTotal(rows[i])) / 2) * (dtMs / HOUR_MS)
  }
  return total
}

// How far a chart's values reach from zero, given each time's row of series
// values. Stacked: the largest stack, positives and negatives apart as Highcharts
// stacks them. Otherwise the largest single value. Nulls count as 0.
export function chartReach(rows: (number | null)[][], stacked: boolean): number {
  let reach = 0
  for (const row of rows) {
    let up = 0
    let down = 0
    for (const value of row.map((v) => v ?? 0)) {
      if (!stacked) reach = Math.max(reach, Math.abs(value || 0))
      else if (value > 0) up += value
      else if (value < 0) down -= value
    }
    reach = Math.max(reach, up, down)
  }
  return reach
}

// Highcharts 13's types only allow the object form, but strings still work. The
// object form would merge in day.boundary, relabelling midnight on hourly axes as the date.
export const DATETIME_LABEL_FORMATS = {
  day: '%e %b',
  hour: '%l%P',
  minute: '%l:%M%P',
} as Highcharts.AxisDateTimeLabelFormatsOptions

// A date-labelled line at each midnight in a run of dispatch timestamps
export function midnightPlotLines(times: string[]): Highcharts.XAxisPlotLinesOptions[] {
  return times
    .filter((time, i) => i > 0 && time.slice(0, 10) !== times[i - 1].slice(0, 10))
    .map((time) => ({
      value: nzLocalMs(time),
      color: 'var(--color-chart-rule)',
      width: 1,
      dashStyle: 'Solid',
      label: {
        text: Highcharts.dateFormat('%e %b', nzLocalMs(time)),
        style: { color: 'var(--color-text-muted)', fontSize: 'var(--font-size-2xs)' },
        y: 14,
      },
      zIndex: 3,
    }))
}

// HighchartsReact calls chart.update() whenever containerProps changes, so an
// inline object would redraw the chart every render
export const CHART_CONTAINER_PROPS = { style: { height: '100%' } }

// Highcharts reflows 100ms after its container resizes, so a chart drawn before
// its panel's layout settles (e.g. SeriesButtonRow collapsing into "+N more") first
// paints at the old size. A ResizeObserver reflows it before the browser paints.
export const FIT_TO_CONTAINER: Highcharts.ChartOptions = {
  reflow: false,
  events: {
    load() {
      const observer = new ResizeObserver(() => this.reflow())
      // The HighchartsReact div the chart was rendered to
      observer.observe(this.container.parentElement!)
      Highcharts.addEvent(this, 'destroy', () => observer.disconnect())
    },
  },
}

// Months per total for monthly, quarterly and annual views; 0 otherwise
function monthsPer(period: AggregatePeriod | null): number {
  return period === 'monthly' ? 1 : period === 'quarterly' ? 3 : period === 'annual' ? 12 : 0
}

// When the period of a total starting at `ms` ends
function periodEnd(ms: number, period: AggregatePeriod): number {
  if (period === 'daily') return ms + DAY_MS
  if (period === 'weekly') return ms + 7 * DAY_MS
  const start = new Date(ms)
  return Date.UTC(start.getUTCFullYear(), start.getUTCMonth() + monthsPer(period), 1)
}

// Tooltip heading: a timestamp, or the period a total covers. The period
// containing today is still growing, so it's marked "(so far)".
export function tooltipTime(ms: number, period: AggregatePeriod | null): string {
  const soFar = period && periodEnd(ms, period) > nzLocalMs(`${todayNZ()}T00:00:00`) ? ' (so far)' : ''
  switch (period) {
    case 'daily':
      return Highcharts.dateFormat('%a %e %b', ms) + soFar
    case 'weekly':
      return `${Highcharts.dateFormat('%e %b', ms)} – ${Highcharts.dateFormat('%e %b %Y', ms + 6 * DAY_MS)}${soFar}`
    case 'monthly':
      return Highcharts.dateFormat('%B %Y', ms) + soFar
    case 'quarterly': {
      const start = new Date(ms)
      const lastMonth = Date.UTC(start.getUTCFullYear(), start.getUTCMonth() + 2, 1)
      return `${Highcharts.dateFormat('%b', ms)} – ${Highcharts.dateFormat('%b %Y', lastMonth)}${soFar}`
    }
    case 'annual':
      return Highcharts.dateFormat('%Y', ms) + soFar
    default:
      return Highcharts.dateFormat('%e %b %I:%M %p', ms)
  }
}

// Screen reader options (accessibility module, loaded in main.tsx). Charts have
// no titles of their own (panel headers name them), so without `title` each reads as "Chart".
export function chartAccessibility(
  title: string,
  accessibility: Highcharts.AccessibilityOptions,
): Pick<Highcharts.Options, 'lang' | 'accessibility'> {
  return { lang: { accessibility: { defaultChartTitle: title } }, accessibility }
}

// How often a chart has a point: dispatch data's `intervalMs` (see
// dataInterval), or an aggregate view's period
function everyInterval(period: AggregatePeriod | null, intervalMs: number): string {
  switch (period) {
    case 'daily':
      return 'each day'
    case 'weekly':
      return 'each week'
    case 'monthly':
      return 'each month'
    case 'quarterly':
      return 'each quarter'
    case 'annual':
      return 'each year'
    default:
      return intervalMs >= TRADING_PERIOD_MS ? 'every half hour' : 'every 5 minutes'
  }
}

// Screen reader options for a time chart in `unit`. The unit and interval are
// appended to `description`. Points read out with the tooltip's time heading,
// not Highcharts' US-style date.
export function timeChartAccessibility(
  title: string,
  description: string,
  period: AggregatePeriod | null,
  unit: DisplayUnit,
  intervalMs = DISPATCH_INTERVAL_MS,
): Pick<Highcharts.Options, 'lang' | 'accessibility'> {
  return chartAccessibility(title, {
    description: `${description}, in ${unit.label} ${everyInterval(period, intervalMs)}.`,
    // Aggregate points are all at midnight, so the range needs no time
    screenReaderSection: { axisRangeDateFormat: period ? '%e %b %Y' : '%e %b %Y %I:%M %p' },
    point: {
      descriptionFormatter: (point) =>
        `${tooltipTime(point.x, period)}, ${unit.format(point.y ?? 0)}. ${point.series.name}.`,
    },
  })
}

// Months, quarters and years vary in length, but Highcharts gives every column
// the shortest gap's width (February's, or a non-leap year's), leaving thin gaps
// after longer ones. After layout, widens each `months`-long column to meet its
// neighbours halfway; both round the same midpoint, so edges always meet.
// shapeArgs is typed read-only, but replacing it is what sizes the drawn column.
function fillColumns(series: Highcharts.Series, months: number) {
  const edge = (ms: number) => Math.round(series.xAxis.toPixels(ms, true))
  for (const point of series.points as { x: number; shapeArgs?: Highcharts.SVGAttributes }[]) {
    if (!point.shapeArgs) continue
    const start = new Date(point.x)
    const prev = Date.UTC(start.getUTCFullYear(), start.getUTCMonth() - months, 1)
    const next = Date.UTC(start.getUTCFullYear(), start.getUTCMonth() + months, 1)
    const left = edge((prev + point.x) / 2)
    const right = edge((point.x + next) / 2)
    point.shapeArgs = { ...point.shapeArgs, x: left, width: right - left }
  }
}

// Sizes monthly, quarterly and annual columns (see fillColumns). The event isn't
// in Highcharts' types, but any function under `events` is registered, and
// columns fire it after layout.
export function columnFillEvents(period: AggregatePeriod | null): Highcharts.SeriesEventsOptionsObject | undefined {
  const months = monthsPer(period)
  if (!months) return undefined
  return {
    afterColumnTranslate(this: Highcharts.Series) {
      fillColumns(this, months)
    },
  } as Highcharts.SeriesEventsOptionsObject
}
